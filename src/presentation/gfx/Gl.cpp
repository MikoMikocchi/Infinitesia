namespace
{
template <typename Function>
void Load(const char *name, Function &function, std::vector<std::string> &missing)
{
	function = reinterpret_cast<Function>(SDL_GL_GetProcAddress(name));
	if (function == nullptr)
	{
		missing.emplace_back(name);
	}
}
} // namespace

bool LoadFunctions(std::string *error)
{
	std::vector<std::string> missing;

#define INFINITESIA_LOAD_GL(type, name) Load<type>("gl" #name, name, missing)
	INFINITESIA_LOAD_GL(PFNGLGENBUFFERSPROC, GenBuffers);
	INFINITESIA_LOAD_GL(PFNGLBINDBUFFERPROC, BindBuffer);
	INFINITESIA_LOAD_GL(PFNGLBUFFERDATAPROC, BufferData);
	INFINITESIA_LOAD_GL(PFNGLBUFFERSUBDATAPROC, BufferSubData);
	INFINITESIA_LOAD_GL(PFNGLDELETEBUFFERSPROC, DeleteBuffers);

	INFINITESIA_LOAD_GL(PFNGLGENVERTEXARRAYSPROC, GenVertexArrays);
	INFINITESIA_LOAD_GL(PFNGLBINDVERTEXARRAYPROC, BindVertexArray);
	INFINITESIA_LOAD_GL(PFNGLDELETEVERTEXARRAYSPROC, DeleteVertexArrays);
	INFINITESIA_LOAD_GL(PFNGLENABLEVERTEXATTRIBARRAYPROC, EnableVertexAttribArray);
	INFINITESIA_LOAD_GL(PFNGLDISABLEVERTEXATTRIBARRAYPROC, DisableVertexAttribArray);
	INFINITESIA_LOAD_GL(PFNGLVERTEXATTRIBPOINTERPROC, VertexAttribPointer);

	INFINITESIA_LOAD_GL(PFNGLCREATESHADERPROC, CreateShader);
	INFINITESIA_LOAD_GL(PFNGLSHADERSOURCEPROC, ShaderSource);
	INFINITESIA_LOAD_GL(PFNGLCOMPILESHADERPROC, CompileShader);
	INFINITESIA_LOAD_GL(PFNGLGETSHADERIVPROC, GetShaderiv);
	INFINITESIA_LOAD_GL(PFNGLGETSHADERINFOLOGPROC, GetShaderInfoLog);
	INFINITESIA_LOAD_GL(PFNGLDELETESHADERPROC, DeleteShader);

	INFINITESIA_LOAD_GL(PFNGLCREATEPROGRAMPROC, CreateProgram);
	INFINITESIA_LOAD_GL(PFNGLATTACHSHADERPROC, AttachShader);
	INFINITESIA_LOAD_GL(PFNGLLINKPROGRAMPROC, LinkProgram);
	INFINITESIA_LOAD_GL(PFNGLGETPROGRAMIVPROC, GetProgramiv);
	INFINITESIA_LOAD_GL(PFNGLGETPROGRAMINFOLOGPROC, GetProgramInfoLog);
	INFINITESIA_LOAD_GL(PFNGLDELETEPROGRAMPROC, DeleteProgram);
	INFINITESIA_LOAD_GL(PFNGLUSEPROGRAMPROC, UseProgram);
	INFINITESIA_LOAD_GL(PFNGLBINDATTRIBLOCATIONPROC, BindAttribLocation);
	INFINITESIA_LOAD_GL(PFNGLGETATTRIBLOCATIONPROC, GetAttribLocation);

	INFINITESIA_LOAD_GL(PFNGLGETUNIFORMLOCATIONPROC, GetUniformLocation);
	INFINITESIA_LOAD_GL(PFNGLUNIFORM1IPROC, Uniform1i);
	INFINITESIA_LOAD_GL(PFNGLUNIFORM1FPROC, Uniform1f);
	INFINITESIA_LOAD_GL(PFNGLUNIFORM2FPROC, Uniform2f);
	INFINITESIA_LOAD_GL(PFNGLUNIFORM3FPROC, Uniform3f);
	INFINITESIA_LOAD_GL(PFNGLUNIFORM4FPROC, Uniform4f);
	INFINITESIA_LOAD_GL(PFNGLUNIFORMMATRIX4FVPROC, UniformMatrix4fv);

	INFINITESIA_LOAD_GL(PFNGLACTIVETEXTUREPROC, ActiveTexture);
	INFINITESIA_LOAD_GL(PFNGLGENERATEMIPMAPPROC, GenerateMipmap);

	INFINITESIA_LOAD_GL(PFNGLBLENDFUNCSEPARATEPROC, BlendFuncSeparate);
	INFINITESIA_LOAD_GL(PFNGLBLENDEQUATIONPROC, BlendEquation);
	INFINITESIA_LOAD_GL(PFNGLBLENDEQUATIONSEPARATEPROC, BlendEquationSeparate);
	INFINITESIA_LOAD_GL(PFNGLDRAWBUFFERSPROC, DrawBuffers);

	INFINITESIA_LOAD_GL(PFNGLGENFRAMEBUFFERSPROC, GenFramebuffers);
	INFINITESIA_LOAD_GL(PFNGLBINDFRAMEBUFFERPROC, BindFramebuffer);
	INFINITESIA_LOAD_GL(PFNGLFRAMEBUFFERTEXTURE2DPROC, FramebufferTexture2D);
	INFINITESIA_LOAD_GL(PFNGLCHECKFRAMEBUFFERSTATUSPROC, CheckFramebufferStatus);
	INFINITESIA_LOAD_GL(PFNGLDELETEFRAMEBUFFERSPROC, DeleteFramebuffers);

	INFINITESIA_LOAD_GL(PFNGLGENRENDERBUFFERSPROC, GenRenderbuffers);
	INFINITESIA_LOAD_GL(PFNGLBINDRENDERBUFFERPROC, BindRenderbuffer);
	INFINITESIA_LOAD_GL(PFNGLRENDERBUFFERSTORAGEPROC, RenderbufferStorage);
	INFINITESIA_LOAD_GL(PFNGLFRAMEBUFFERRENDERBUFFERPROC, FramebufferRenderbuffer);
	INFINITESIA_LOAD_GL(PFNGLDELETERENDERBUFFERSPROC, DeleteRenderbuffers);
	INFINITESIA_LOAD_GL(PFNGLBLITFRAMEBUFFERPROC, BlitFramebuffer);
#undef INFINITESIA_LOAD_GL

	if (missing.empty())
	{
		return true;
	}

	if (error != nullptr)
	{
		*error = "missing ";
		for (std::size_t index = 0; index < missing.size(); ++index)
		{
			if (index != 0)
			{
				*error += ", ";
			}
			*error += missing[index];
		}
	}
	return false;
}
